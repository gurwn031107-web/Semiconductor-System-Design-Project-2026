module tb_multicycle;
    logic clk=0, rst_n=0;
    always #5 clk=~clk;
    logic [31:0] instr_code, instr_addr, daddr, dwdata, drdata;
    logic dwe;
    logic [2:0] itype;
    logic [31:0] rom[0:255];
    logic [31:0] expected_rf[0:31], expected_mem[0:127];
    integer commits=0;
    rv32i_cpu dut(.*);
    data_mem ram(.*);
    assign instr_code=rom[instr_addr[9:2]];

    task check_pc(input logic [31:0] wanted);
        do @(negedge clk); while (dut.U_CONTROL_UNIT.c_state != 1);
        if (instr_addr !== wanted)
            $fatal(1,"PC expected %h got %h",wanted,instr_addr);
    endtask

    task check_commit;
        do @(negedge clk); while (dut.U_CONTROL_UNIT.c_state != 0);
        for (int i=1;i<32;i++)
            if (dut.U_DATAPATH.U_REG_FILE.ram_file[i] !== expected_rf[i])
                $fatal(1,"PC %h x%0d expected %h got %h",instr_addr,i,
                    expected_rf[i],dut.U_DATAPATH.U_REG_FILE.ram_file[i]);
        for (int i=0;i<128;i++)
            if (ram.dmem[i] !== expected_mem[i])
                $fatal(1,"PC %h memory[%0d] mismatch",instr_addr,i);
        if (dut.U_DATAPATH.U_REG_FILE.rd1 !== 0 && instr_code[19:15]==0)
            $fatal(1,"x0 read is not zero");
        commits++;
    endtask

    // Check externally visible side-effect timing independently of results.
    always @(negedge clk) if (rst_n) begin
        if (dut.pc_en !== (dut.U_CONTROL_UNIT.c_state == 0))
            $fatal(1,"pc_en outside FETCH");
        if (dwe && dut.U_CONTROL_UNIT.c_state != 3)
            $fatal(1,"RAM write outside MEM");
        if (dut.rf_we && dut.U_CONTROL_UNIT.c_state != 2 && dut.U_CONTROL_UNIT.c_state != 4)
            $fatal(1,"RF write outside EXECUTE/WB");
    end

